"""The web app as a C++ source (docs/board/wifi-and-updates-v1.md#the-served-web-app).

    tools/web_assets.py --dist web/dist --out web_assets.cpp --header lib/ZenitNet/src/net_http.h

Gzips every file of the built web app, in a fixed order and without timestamps, and writes one source with the bytes of
each, its path, its media type and whether its name carries a content hash. The output is the same for the same input.
Fails when the folder holds no index.html, which means the web app was not built.

Standard library only.
"""

import argparse
import gzip
import sys
from pathlib import Path

TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".svg": "image/svg+xml",
    ".json": "application/json",
    ".txt": "text/plain; charset=utf-8",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".woff2": "font/woff2",
    ".webmanifest": "application/manifest+json",
}
# What a web app of ours does not need on a board: maps and anything else not served.
SKIPPED_SUFFIXES = (".map",)
MAX_PATH = 127


class AssetsError(Exception):
    pass


def collect(dist):
    """(path, media type, gzipped bytes, immutable) of each file, sorted by path."""
    root = Path(dist)
    if not (root / "index.html").is_file():
        raise AssetsError(f"{root}/index.html is missing: build the web app first (just web-build)")
    files = []
    for path in sorted(p for p in root.rglob("*") if p.is_file() and not p.is_symlink()):
        relative = path.relative_to(root).as_posix()
        if relative.endswith(SKIPPED_SUFFIXES):
            continue
        if len(relative) > MAX_PATH or any(ord(c) < 0x21 or ord(c) > 0x7E or c == "\\" for c in relative):
            raise AssetsError(f"{relative}: the path is not one the board can serve")
        media = TYPES.get(path.suffix.lower())
        if media is None:
            raise AssetsError(f"{relative}: no media type for '{path.suffix}'")
        data = gzip.compress(path.read_bytes(), compresslevel=9, mtime=0)
        files.append((relative, media, data, relative.startswith("assets/")))
    return files


def render(files, header):
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by tools/web_assets.py from the built web app. Do not edit.",
        "",
        f'#include "{header}"',
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace web_assets",
        "{",
        "",
    ]
    for index, (_, _, data, _) in enumerate(files):
        lines.append(f"static const uint8_t DATA_{index}[] = {{")
        for start in range(0, len(data), 24):
            lines.append("    " + ",".join(str(b) for b in data[start : start + 24]) + ",")
        lines.append("};")
    lines += ["", "extern const zenit::net::Asset ASSETS[] = {"]
    for index, (path, media, data, immutable) in enumerate(files):
        lines.append(f'    {{"{path}", "{media}", DATA_{index}, {len(data)}, {"true" if immutable else "false"}}},')
    lines += ["};", f"extern const size_t COUNT = {len(files)};", "", "} // namespace web_assets", ""]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description="Write the built web app as a C++ source.")
    parser.add_argument("--dist", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--header", required=True, help="the path of net_http.h, as the source includes it")
    args = parser.parse_args(argv)
    try:
        text = render(collect(args.dist), args.header)
    except AssetsError as error:
        print(f"web_assets: {error}", file=sys.stderr)
        return 1
    # Written only when it changes, so an unchanged web app does not rebuild the firmware's object.
    if not args.out.is_file() or args.out.read_text(encoding="utf-8") != text:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
